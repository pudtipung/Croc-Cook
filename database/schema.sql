-- 2.1 ตารางผู้ดูแลระบบ (admins)
-- สำหรับจัดการข้อมูลสูตรอาหาร วัตถุดิบ และหมวดหมู่
CREATE TABLE IF NOT EXISTS `admins` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `username` VARCHAR(50) NOT NULL COMMENT 'ชื่อบัญชีสำหรับเข้าสู่ระบบ (ต้องไม่ซ้ำ)',
    `password` VARCHAR(255) NOT NULL COMMENT 'รหัสผ่านที่เข้ารหัสด้วย bcrypt (password_hash)',
    `name` VARCHAR(100) NOT NULL COMMENT 'ชื่อ-นามสกุล หรือชื่อแสดงของผู้ดูแลระบบ',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'วันเวลาที่สร้างบัญชี',
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'วันเวลาที่อัปเดตข้อมูลล่าสุด',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_admins_username` (`username`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='ตารางบัญชีผู้ดูแลระบบ';

-- 2.2 ตารางหมวดหมู่อาหาร (categories)
-- เช่น เมนูต้มและแกง, เมนูผัด, เมนูทอด, เมนูยำ, เมนูน้ำพริก
CREATE TABLE IF NOT EXISTS `categories` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `name` VARCHAR(100) NOT NULL COMMENT 'ชื่อหมวดหมู่อาหาร',
    `description` TEXT DEFAULT NULL COMMENT 'คำอธิบายหมวดหมู่',
    `icon` VARCHAR(50) DEFAULT 'bi-egg-fried' COMMENT 'คลาสไอคอนจาก Bootstrap Icons เช่น bi-fire, bi-cup-hot',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'วันเวลาที่สร้าง',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_categories_name` (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='ตารางหมวดหมู่อาหาร';

-- 2.3 ตารางสูตรอาหาร (recipes)
-- เก็บข้อมูลหลักของเมนูอาหาร เช่น ชื่อ เวลาที่ใช้ จำนวนจาน และวิธีปรุง
CREATE TABLE IF NOT EXISTS `recipes` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `category_id` INT NOT NULL COMMENT 'รหัสหมวดหมู่อาหาร (Foreign Key เชื่อมกับ categories)',
    `title` VARCHAR(200) NOT NULL COMMENT 'ชื่อเมนูอาหาร',
    `description` TEXT DEFAULT NULL COMMENT 'คำอธิบายเมนูอาหารโดยย่อ',
    `image` VARCHAR(255) DEFAULT NULL COMMENT 'ชื่อไฟล์รูปภาพหรือ URL ของรูปภาพ',
    `cooking_time` INT DEFAULT 15 COMMENT 'เวลาที่ใช้ในการปรุงอาหาร (หน่วย: นาที)',
    `servings` INT DEFAULT 1 COMMENT 'จำนวนหน่วยบริโภค (หน่วย: จาน/ที่)',
    `instructions` TEXT NOT NULL COMMENT 'ขั้นตอนและวิธีปรุงอาหารอย่างละเอียด',
    `views` INT NOT NULL DEFAULT 0 COMMENT 'ยอดเข้าชมสูตรอาหาร',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'วันเวลาที่เพิ่มเมนู',
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'วันเวลาที่แก้ไขล่าสุด',
    PRIMARY KEY (`id`),
    KEY `idx_recipes_category_id` (`category_id`),
    CONSTRAINT `fk_recipes_category` FOREIGN KEY (`category_id`) 
        REFERENCES `categories` (`id`) 
        ON UPDATE CASCADE 
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='ตารางสูตรอาหาร';

-- 2.4 ตารางวัตถุดิบ (ingredients)
-- คลังวัตถุดิบทั้งหมดที่ใช้สำหรับค้นหาและจับคู่เมนู
CREATE TABLE IF NOT EXISTS `ingredients` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `name` VARCHAR(100) NOT NULL COMMENT 'ชื่อวัตถุดิบ เช่น หมูสับ, ไข่ไก่, กะปิ',
    `type` ENUM('main', 'seasoning') NOT NULL DEFAULT 'main' COMMENT 'ประเภทวัตถุดิบ: main = วัตถุดิบหลัก, seasoning = เครื่องปรุงรส',
    `category_group` VARCHAR(50) NOT NULL DEFAULT 'ทั่วไป' COMMENT 'กลุ่มของวัตถุดิบ เช่น เนื้อสัตว์, ผักและสมุนไพร, เครื่องปรุงรส, ไข่และแป้ง',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'วันเวลาที่สร้าง',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_ingredients_name` (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='ตารางคลังวัตถุดิบ';

-- 2.5 ตารางเชื่อมสูตรอาหารกับวัตถุดิบ (recipe_ingredients)
-- ตารางความสัมพันธ์แบบ Many-to-Many ระหว่าง recipes กับ ingredients
CREATE TABLE IF NOT EXISTS `recipe_ingredients` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `recipe_id` INT NOT NULL COMMENT 'รหัสสูตรอาหาร (Foreign Key เชื่อมกับ recipes)',
    `ingredient_id` INT NOT NULL COMMENT 'รหัสวัตถุดิบ (Foreign Key เชื่อมกับ ingredients)',
    `quantity` VARCHAR(50) DEFAULT NULL COMMENT 'ปริมาณที่ใช้ เช่น 200, 1-2, เล็กน้อย',
    `unit` VARCHAR(50) DEFAULT NULL COMMENT 'หน่วยวัด เช่น กรัม, ช้อนโต๊ะ, ฟอง, ถ้วย',
    `is_essential` TINYINT(1) NOT NULL DEFAULT 1 COMMENT 'สถานะความจำเป็น: 1 = วัตถุดิบจำเป็น/ขาดไม่ได้, 0 = วัตถุดิบทางเลือก/เครื่องปรุงเสริม',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_recipe_ingredient` (`recipe_id`, `ingredient_id`),
    KEY `idx_ri_ingredient_id` (`ingredient_id`),
    CONSTRAINT `fk_ri_recipe` FOREIGN KEY (`recipe_id`) 
        REFERENCES `recipes` (`id`) 
        ON UPDATE CASCADE 
        ON DELETE CASCADE,
    CONSTRAINT `fk_ri_ingredient` FOREIGN KEY (`ingredient_id`) 
        REFERENCES `ingredients` (`id`) 
        ON UPDATE CASCADE 
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='ตารางเชื่อมโยงสูตรอาหารกับวัตถุดิบ';

